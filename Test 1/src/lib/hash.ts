/**
 * Детерминированный псевдошум 0..1.
 *
 * Нужен всем canvas-секциям: разлёт частиц обязан совпадать при каждом входе
 * в секцию и на каждой перезагрузке, иначе «шум» выглядит как случайный баг,
 * а скриншот-регрессия превращается в лотерею.
 */
export const hash01 = (value: number) => {
  const x = Math.sin(value * 127.1 + 311.7) * 43758.5453
  return x - Math.floor(x)
}
